import io
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session, joinedload
from typing import List
from datetime import datetime
from database import get_db
from models import Report, Inspection
from schemas import ReportCreate, ReportOut
from deps import get_current_user

router = APIRouter(prefix="/reports", tags=["Reports"])


@router.get("", response_model=List[ReportOut])
def list_reports(db: Session = Depends(get_db), _=Depends(get_current_user)):
    return db.query(Report).order_by(Report.generated_at.desc()).all()


@router.get("/{id}", response_model=ReportOut)
def get_report(id: str, db: Session = Depends(get_db), _=Depends(get_current_user)):
    r = db.query(Report).filter(Report.id == id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")
    return r


@router.post("", response_model=ReportOut, status_code=201)
def create_report(body: ReportCreate, db: Session = Depends(get_db), _=Depends(get_current_user)):
    ins = db.query(Inspection).filter(Inspection.id == body.inspection_id).first()
    if not ins:
        raise HTTPException(status_code=404, detail="Inspection not found")
    r = Report(
        inspection_id=body.inspection_id,
        generated_by=body.generated_by,
        summary=body.summary,
        recommendations=body.recommendations or [],
        status="draft",
    )
    db.add(r)
    db.commit()
    db.refresh(r)
    return r


@router.patch("/{id}/finalize", response_model=ReportOut)
def finalize_report(id: str, db: Session = Depends(get_db), _=Depends(get_current_user)):
    r = db.query(Report).filter(Report.id == id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")
    r.status = "finalized"
    db.commit()
    db.refresh(r)
    return r


@router.patch("/{id}/sign", response_model=ReportOut)
def sign_report(id: str, signed_by: str, db: Session = Depends(get_db), _=Depends(get_current_user)):
    r = db.query(Report).filter(Report.id == id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")
    r.signed_by = signed_by
    r.signed_at = datetime.utcnow()
    db.commit()
    db.refresh(r)
    return r


@router.patch("/{id}/share", response_model=ReportOut)
def share_report(id: str, db: Session = Depends(get_db), _=Depends(get_current_user)):
    r = db.query(Report).filter(Report.id == id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")
    r.status = "shared"
    db.commit()
    db.refresh(r)
    return r


@router.get("/{id}/pdf")
def download_pdf(id: str, db: Session = Depends(get_db), _=Depends(get_current_user)):
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
    from reportlab.lib.enums import TA_LEFT, TA_CENTER

    r = db.query(Report).options(joinedload(Report.inspection).joinedload(Inspection.aircraft), joinedload(Report.inspection).joinedload(Inspection.defects)).filter(Report.id == id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20*mm, rightMargin=20*mm, topMargin=20*mm, bottomMargin=20*mm)
    styles = getSampleStyleSheet()

    title_style  = ParagraphStyle("title",  parent=styles["Title"],   fontSize=20, spaceAfter=4, textColor=colors.HexColor("#1e3a5f"))
    h2_style     = ParagraphStyle("h2",     parent=styles["Heading2"], fontSize=13, spaceAfter=4, spaceBefore=10, textColor=colors.HexColor("#1e3a5f"))
    body_style   = ParagraphStyle("body",   parent=styles["Normal"],   fontSize=10, spaceAfter=3, leading=14)
    label_style  = ParagraphStyle("label",  parent=styles["Normal"],   fontSize=9,  textColor=colors.HexColor("#6b7280"))

    ins = r.inspection
    ac  = ins.aircraft if ins else None

    story = []
    story.append(Paragraph("Aerosepct Inspection Report", title_style))
    story.append(Paragraph(f"Report ID: {r.id}", label_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#e5e7eb"), spaceAfter=8))

    # Meta table
    meta = [
        ["Generated", r.generated_at.strftime("%Y-%m-%d %H:%M UTC"), "Generated By", r.generated_by],
        ["Status",    r.status.capitalize(),                           "Signed By",    r.signed_by or "—"],
    ]
    if ac:
        meta.append(["Aircraft", f"{ac.manufacturer} {ac.model}", "Registration", ac.registration])
    meta_tbl = Table(meta, colWidths=[35*mm, 65*mm, 35*mm, 65*mm])
    meta_tbl.setStyle(TableStyle([
        ("FONTSIZE",    (0, 0), (-1, -1), 9),
        ("TEXTCOLOR",   (0, 0), (0, -1), colors.HexColor("#6b7280")),
        ("TEXTCOLOR",   (2, 0), (2, -1), colors.HexColor("#6b7280")),
        ("FONTNAME",    (1, 0), (1, -1), "Helvetica-Bold"),
        ("FONTNAME",    (3, 0), (3, -1), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING",    (0, 0), (-1, -1), 4),
    ]))
    story.append(meta_tbl)
    story.append(Spacer(1, 6*mm))

    # Summary
    if r.summary:
        story.append(Paragraph("Summary", h2_style))
        story.append(Paragraph(r.summary, body_style))
        story.append(Spacer(1, 4*mm))

    # Recommendations
    if r.recommendations:
        story.append(Paragraph("Recommendations", h2_style))
        for rec in r.recommendations:
            story.append(Paragraph(f"• {rec}", body_style))
        story.append(Spacer(1, 4*mm))

    # Defects table
    if ins and ins.defects:
        story.append(Paragraph("Detected Defects", h2_style))
        defect_rows = [["Type", "Severity", "Location", "Depth (mm)", "Confidence"]]
        for d in ins.defects:
            defect_rows.append([
                d.type.replace("_", " ").title(),
                d.severity.capitalize(),
                d.location,
                str(round(d.depth, 1)) if d.depth else "—",
                f"{round(d.confidence * 100)}%" if d.confidence else "—",
            ])
        dtbl = Table(defect_rows, colWidths=[35*mm, 25*mm, 60*mm, 25*mm, 25*mm])
        dtbl.setStyle(TableStyle([
            ("BACKGROUND",    (0, 0), (-1, 0), colors.HexColor("#1e3a5f")),
            ("TEXTCOLOR",     (0, 0), (-1, 0), colors.white),
            ("FONTNAME",      (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE",      (0, 0), (-1, -1), 9),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f9fafb")]),
            ("GRID",          (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING",    (0, 0), (-1, -1), 5),
        ]))
        story.append(dtbl)

    doc.build(story)
    buf.seek(0)
    return StreamingResponse(
        buf,
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename=report-{id[:8]}.pdf"},
    )
