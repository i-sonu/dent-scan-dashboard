// Simulated real-time telemetry
export function generateTelemetry(points = 60): TelemetryData[] {
  return Array.from({ length: points }, (_, i) => ({
    timestamp: Date.now() - (points - i) * 5000,
    altitude: 8 + Math.sin(i * 0.2) * 0.5 + Math.random() * 0.2,
    battery: 92 - i * 0.5 + Math.random() * 0.3,
    speed: 6 + Math.sin(i * 0.3) * 1.5 + Math.random() * 0.5,
    signal: 95 - Math.random() * 5,
    latitude: 40.6413 + i * 0.0001,
    longitude: -73.7781 + i * 0.00015,
    pitch: Math.sin(i * 0.15) * 3,
    roll: Math.cos(i * 0.12) * 2,
    yaw: (i * 6) % 360,
  }))
}
